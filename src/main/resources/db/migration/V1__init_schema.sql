-- Written to run unchanged on both PostgreSQL and H2 (PostgreSQL mode).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE doctors (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    specialization VARCHAR(100) NOT NULL
);

CREATE TABLE slots (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id  BIGINT      NOT NULL REFERENCES doctors (id),
    start_time TIMESTAMP   NOT NULL,
    end_time   TIMESTAMP   NOT NULL,
    status     VARCHAR(20) NOT NULL,
    version    BIGINT      NOT NULL DEFAULT 0,
    -- a doctor can never have two slots starting at the same time
    CONSTRAINT uk_slots_doctor_start UNIQUE (doctor_id, start_time)
);

CREATE TABLE appointments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id         BIGINT      NOT NULL REFERENCES slots (id),
    patient_id      BIGINT      NOT NULL REFERENCES users (id),
    status          VARCHAR(20) NOT NULL,
    idempotency_key VARCHAR(100),
    created_at      TIMESTAMP   NOT NULL,
    cancelled_at    TIMESTAMP,
    reminder_sent   BOOLEAN     NOT NULL DEFAULT FALSE,
    -- the same patient re-sending the same Idempotency-Key can never create a second row
    CONSTRAINT uk_appointments_patient_idem UNIQUE (patient_id, idempotency_key)
);

CREATE INDEX idx_appointments_patient ON appointments (patient_id);
CREATE INDEX idx_appointments_slot ON appointments (slot_id);
